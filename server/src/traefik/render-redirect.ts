import { mkdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { stringify } from 'yaml'
import { getAccessListForRender, mwAccessAuthName, mwAccessIpName } from '../access-lists.js'
import { cfg } from '../config.js'
import type { RedirectionHost } from '../redirections.js'
import { addDenyRouters, certResolverName, escapeRuleLiteral, hostRule } from './rules.js'

function safeId(id: string): string {
  return id.replace(/[^a-zA-Z0-9_-]/g, '')
}

export function renderRedirectYaml(host: RedirectionHost): string {
  mkdirSync(cfg.vhostsDir, { recursive: true })
  const sid = safeId(host.id)
  const mwRedir = `mw-${sid}-redir`
  const mwHttps = `mw-${sid}-https`
  const chain: string[] = []
  const middlewares: Record<string, unknown> = {}
  const routers: Record<string, unknown> = {}

  const pathPart = host.forward_path?.startsWith('/') ? host.forward_path : `/${host.forward_path || ''}`
  const targetBase = `${host.forward_scheme}://${host.forward_host}${pathPart === '/' ? '' : pathPart}`

  if (host.preserve_path) {
    middlewares[mwRedir] = {
      redirectRegex: {
        regex: '^https?://[^/]+(.*)',
        replacement: `${targetBase}\${1}`,
        permanent: host.status_code === 301,
      },
    }
  } else {
    middlewares[mwRedir] = {
      redirectRegex: {
        regex: '.*',
        replacement: targetBase || `${host.forward_scheme}://${host.forward_host}/`,
        permanent: host.status_code === 301,
      },
    }
  }

  if (host.access_list_id) {
    const acl = getAccessListForRender(host.access_list_id)
    if (acl?.enabled) {
      if (acl.hasIpAllow) chain.push(mwAccessIpName(acl.id))
      if (acl.hasAuth) chain.push(mwAccessAuthName(acl.id))
      let prio = 100
      acl.deny.forEach((ip, i) => {
        addDenyRouters(routers, {
          sid,
          suffix: `denyip-${i}`,
          rule: `(${hostRule(host.domain_names)}) && ClientIP(\`${escapeRuleLiteral(ip)}\`)`,
          service: 'noop@internal',
          priority: prio++,
        })
      })
    }
  }

  const redirChain = [...chain, mwRedir]

  if (host.ssl_forced) {
    middlewares[mwHttps] = {
      redirectScheme: { scheme: 'https', permanent: true },
    }
    routers[`rt-${sid}-http`] = {
      rule: hostRule(host.domain_names),
      entryPoints: ['web'],
      middlewares: [mwHttps],
      service: 'noop@internal',
      priority: 1,
    }
  } else {
    routers[`rt-${sid}-http`] = {
      rule: hostRule(host.domain_names),
      entryPoints: ['web'],
      middlewares: redirChain,
      service: 'noop@internal',
      priority: 1,
    }
  }

  const httpsRouter: Record<string, unknown> = {
    rule: hostRule(host.domain_names),
    entryPoints: ['websecure'],
    middlewares: redirChain,
    service: 'noop@internal',
    priority: 10,
    tls: {},
  }
  const cr = certResolverName(host.cert_resolver)
  if (cr) {
    httpsRouter.tls = {
      certResolver: cr,
      domains: [{ main: host.domain_names[0], sans: host.domain_names.slice(1) }],
    }
  }
  routers[`rt-${sid}`] = httpsRouter

  const doc = {
    http: {
      routers,
      middlewares,
    },
  }

  const yaml = `# generated by tpm — redirection — do not edit\n${stringify(doc)}`
  const finalPath = path.join(cfg.vhostsDir, `${sid}.yml`)
  const tmpPath = `${finalPath}.tmp`
  writeFileSync(tmpPath, yaml, 'utf8')
  renameSync(tmpPath, finalPath)
  return finalPath
}

export function removeRedirectYaml(id: string): void {
  const finalPath = path.join(cfg.vhostsDir, `${safeId(id)}.yml`)
  try {
    unlinkSync(finalPath)
  } catch {
    // ignore
  }
}
