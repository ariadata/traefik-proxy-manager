import { chmodSync, mkdirSync, renameSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { stringify } from 'yaml'
import {
  listAccessListsForRender,
  mwAccessAuthName,
  mwAccessIpName,
} from '../access-lists.js'
import { cfg } from '../config.js'
import { getDb } from '../db.js'

const FILE = '_tpm_middlewares.yml'

export function mwHeaderName(id: string): string {
  return `tpm-hdr-${id.replace(/[^a-zA-Z0-9]/g, '')}`
}

export function mwWafName(id: string): string {
  return `tpm-waf-${id.replace(/[^a-zA-Z0-9]/g, '')}`
}

export function mwDenyName(): string {
  return 'tpm-deny-all'
}

export { mwAccessAuthName, mwAccessIpName }

export function renderSharedMiddlewares(): void {
  mkdirSync(cfg.vhostsDir, { recursive: true })
  const finalPath = path.join(cfg.vhostsDir, FILE)
  const middlewares: Record<string, unknown> = {
    [mwDenyName()]: {
      ipAllowList: {
        sourceRange: ['255.255.255.255/32'],
      },
    },
  }

  const headers = getDb().prepare(`SELECT * FROM header_rules WHERE enabled = 1`).all() as Array<{
    id: string
    type: string
    header_name: string
    header_value: string
  }>

  for (const h of headers) {
    const name = mwHeaderName(h.id)
    if (h.type === 'request_add') {
      middlewares[name] = { headers: { customRequestHeaders: { [h.header_name]: h.header_value } } }
    } else if (h.type === 'request_remove') {
      middlewares[name] = { headers: { customRequestHeaders: { [h.header_name]: '' } } }
    } else if (h.type === 'response_add') {
      middlewares[name] = { headers: { customResponseHeaders: { [h.header_name]: h.header_value } } }
    } else if (h.type === 'response_remove') {
      middlewares[name] = { headers: { customResponseHeaders: { [h.header_name]: '' } } }
    }
  }

  const wafs = getDb().prepare(`SELECT * FROM waf_profiles WHERE enabled = 1`).all() as Array<{
    id: string
    kind: string
    config_json: string
  }>

  for (const w of wafs) {
    const name = mwWafName(w.id)
    const cfgJson = JSON.parse(w.config_json || '{}') as Record<string, unknown>
    if (w.kind === 'rate_limit') {
      middlewares[name] = {
        rateLimit: {
          average: Number(cfgJson.average ?? 60),
          burst: Number(cfgJson.burst ?? 30),
          period: String(cfgJson.period ?? '1m'),
        },
      }
    } else if (w.kind === 'ip_allow') {
      middlewares[name] = {
        ipAllowList: {
          sourceRange: (cfgJson.source_range as string[]) || ['127.0.0.1/32'],
        },
      }
    } else if (w.kind === 'ip_deny') {
      // Traefik has no native deny-list middleware; hosts attach ClientIP deny routers.
      middlewares[name] = {
        headers: {
          customResponseHeaders: { 'X-TPM-IP-Deny': 'configured' },
        },
      }
    } else if (w.kind === 'security_headers') {
      middlewares[name] = {
        headers: {
          stsSeconds: Number(cfgJson.stsSeconds ?? 31536000),
          browserXssFilter: cfgJson.browserXssFilter !== false,
          contentTypeNosniff: cfgJson.contentTypeNosniff !== false,
          frameDeny: cfgJson.frameDeny !== false,
          referrerPolicy: String(cfgJson.referrerPolicy ?? 'strict-origin-when-cross-origin'),
          forceSTSHeader: true,
        },
      }
    } else if (w.kind === 'bot_ua_path') {
      middlewares[name] = {
        headers: {
          customResponseHeaders: { 'X-TPM-Bot-Shield': 'on' },
        },
      }
    }
  }

  const acls = listAccessListsForRender()
  for (const acl of acls) {
    if (acl.hasIpAllow) {
      middlewares[mwAccessIpName(acl.id)] = {
        ipAllowList: { sourceRange: acl.allow },
      }
    }
    if (acl.hasAuth) {
      middlewares[mwAccessAuthName(acl.id)] = {
        basicAuth: {
          users: acl.basicUsers,
          removeHeader: !acl.passAuth,
        },
      }
    }
  }

  const doc = { http: { middlewares } }
  const yaml = `# generated by tpm — shared middlewares\n${stringify(doc)}`
  const tmp = `${finalPath}.tmp`
  writeFileSync(tmp, yaml, 'utf8')
  chmodSync(tmp, 0o600)
  renameSync(tmp, finalPath)
  try {
    chmodSync(finalPath, 0o600)
  } catch {
    /* ignore */
  }
}
