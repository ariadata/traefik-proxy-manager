import { chmodSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parse, stringify } from 'yaml'
import { cfg } from '../config.js'
import { getDb } from '../db.js'
import { decryptJson } from '../secrets.js'
import { getProvider } from '../providers.js'
import { isSafeEnvKey } from './rules.js'

type ResolverRow = {
  name: string
  provider: string
  acme_email: string
  challenge: string
  credentials_enc: Buffer | null
}

type StreamEpRow = {
  id: string
  protocol: string
  entry_port: number
}

function basePath(): string {
  return path.join(path.dirname(cfg.traefikStatic), 'traefik.base.yml')
}

export function providersEnvPath(): string {
  return path.join(cfg.dataDir, 'traefik-providers.env')
}

export function streamEntryPointName(id: string, protocol: string, entryPort: number): string {
  return `stream-${protocol}-${entryPort}-${id.replace(/[^a-zA-Z0-9]/g, '').slice(0, 8)}`
}

/** Rewrite traefik.yml (resolvers + stream entryPoints) + provider env. Restart advised. */
export function applyTraefikStatic(): boolean {
  mkdirSync(cfg.dataDir, { recursive: true })
  mkdirSync(path.dirname(cfg.traefikStatic), { recursive: true })

  const baseRaw = readFileSync(basePath(), 'utf8')
  const doc = parse(baseRaw) as Record<string, unknown>

  const rows = getDb()
    .prepare(`SELECT name, provider, acme_email, challenge, credentials_enc FROM dns_resolvers`)
    .all() as ResolverRow[]
  const certificatesResolvers: Record<string, unknown> = {}
  const envLines: string[] = ['# generated by tpm — do not edit']

  for (const r of rows) {
    const acme: Record<string, unknown> = {
      email: r.acme_email,
      storage: '/data/acme.json',
    }

    if (r.provider === 'http' || r.challenge === 'http01') {
      acme.httpChallenge = { entryPoint: 'web' }
    } else if (r.challenge === 'tlsalpn01') {
      acme.tlsChallenge = {}
    } else {
      acme.dnsChallenge = {
        provider: r.provider,
        resolvers: ['1.1.1.1:53', '8.8.8.8:53'],
      }
    }

    certificatesResolvers[r.name] = { acme }

    const creds =
      r.credentials_enc && r.credentials_enc.length
        ? (decryptJson<Record<string, string>>(r.credentials_enc) ?? {})
        : {}
    const provider = getProvider(r.provider)
    const allowed = new Set((provider?.fields || []).map((f) => f.key))
    for (const [k, v] of Object.entries(creds)) {
      if (!k || v === undefined || v === '') continue
      if (!isSafeEnvKey(k) || (allowed.size > 0 && !allowed.has(k))) continue
      const safe = String(v).replace(/[\r\n]/g, '').replace(/"/g, '\\"')
      envLines.push(`${k}="${safe}"`)
    }
  }

  if (Object.keys(certificatesResolvers).length > 0) {
    doc.certificatesResolvers = certificatesResolvers
  } else {
    delete doc.certificatesResolvers
  }

  const entryPoints = {
    ...((doc.entryPoints as Record<string, unknown>) || {}),
  }
  const streamRows = getDb()
    .prepare(`SELECT id, protocol, entry_port FROM streams WHERE enabled = 1`)
    .all() as StreamEpRow[]
  for (const s of streamRows) {
    const name = streamEntryPointName(s.id, s.protocol, s.entry_port)
    entryPoints[name] =
      s.protocol === 'udp' ? { address: `:${s.entry_port}/udp` } : { address: `:${s.entry_port}` }
  }
  doc.entryPoints = entryPoints

  // Drop legacy experimental plugins block if present in older generated files / base
  delete doc.experimental

  const out = `# generated by tpm from traefik.base.yml — do not edit by hand\n${stringify(doc)}`
  const tmp = `${cfg.traefikStatic}.tmp`
  writeFileSync(tmp, out, 'utf8')
  renameSync(tmp, cfg.traefikStatic)

  const envFile = providersEnvPath()
  const envTmp = `${envFile}.tmp`
  writeFileSync(envTmp, `${envLines.join('\n')}\n`, 'utf8')
  chmodSync(envTmp, 0o600)
  renameSync(envTmp, envFile)
  try {
    chmodSync(envFile, 0o600)
  } catch {
    /* ignore */
  }

  return true
}
