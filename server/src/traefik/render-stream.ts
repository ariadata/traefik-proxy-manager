import { mkdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { stringify } from 'yaml'
import { cfg } from '../config.js'
import type { Stream } from '../streams.js'
import { certResolverName, hostSniRule } from './rules.js'
import { streamEntryPointName } from './static.js'

function safeId(id: string): string {
  return id.replace(/[^a-zA-Z0-9_-]/g, '')
}

export function renderStreamYaml(stream: Stream): string {
  mkdirSync(cfg.vhostsDir, { recursive: true })
  const sid = safeId(stream.id)
  const ep = streamEntryPointName(stream.id, stream.protocol, stream.entry_port)
  const routerName = `rt-${sid}`
  const serviceName = `svc-${sid}`

  let doc: Record<string, unknown>

  if (stream.protocol === 'udp') {
    doc = {
      udp: {
        routers: {
          [routerName]: {
            entryPoints: [ep],
            service: serviceName,
          },
        },
        services: {
          [serviceName]: {
            loadBalancer: {
              servers: [{ address: `${stream.forward_host}:${stream.forward_port}` }],
            },
          },
        },
      },
    }
  } else {
    // Non-TLS TCP must use HostSNI(`*`); specific SNI requires TLS.
    const rule =
      stream.tls_mode === 'off' || stream.sni_hosts.length === 0
        ? 'HostSNI(`*`)'
        : hostSniRule(stream.sni_hosts)

    const router: Record<string, unknown> = {
      entryPoints: [ep],
      rule,
      service: serviceName,
    }

    if (stream.tls_mode === 'passthrough') {
      router.tls = { passthrough: true }
    } else if (stream.tls_mode === 'terminate') {
      const cr = certResolverName(stream.cert_resolver)
      router.tls = cr
        ? {
            certResolver: cr,
            domains: [
              {
                main: stream.sni_hosts[0],
                sans: stream.sni_hosts.slice(1),
              },
            ],
          }
        : {}
    }

    doc = {
      tcp: {
        routers: { [routerName]: router },
        services: {
          [serviceName]: {
            loadBalancer: {
              servers: [{ address: `${stream.forward_host}:${stream.forward_port}` }],
            },
          },
        },
      },
    }
  }

  const yaml = `# generated by tpm — stream — do not edit\n${stringify(doc)}`
  const finalPath = path.join(cfg.vhostsDir, `stream-${sid}.yml`)
  const tmpPath = `${finalPath}.tmp`
  writeFileSync(tmpPath, yaml, 'utf8')
  renameSync(tmpPath, finalPath)
  return finalPath
}

export function removeStreamYaml(id: string): void {
  const finalPath = path.join(cfg.vhostsDir, `stream-${safeId(id)}.yml`)
  try {
    unlinkSync(finalPath)
  } catch {
    // ignore
  }
}
