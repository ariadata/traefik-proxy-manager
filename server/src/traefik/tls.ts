import { mkdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { stringify } from 'yaml'
import { cfg } from '../config.js'
import { getDb } from '../db.js'

const FILE = '_tpm_tls.yml'

export function renderTlsCertsYaml(): void {
  mkdirSync(cfg.vhostsDir, { recursive: true })
  const finalPath = path.join(cfg.vhostsDir, FILE)
  const rows = getDb()
    .prepare(
      `SELECT cert_path, key_path FROM certificates
       WHERE kind = 'custom' AND cert_path IS NOT NULL AND key_path IS NOT NULL`,
    )
    .all() as { cert_path: string; key_path: string }[]

  if (rows.length === 0) {
    try {
      unlinkSync(finalPath)
    } catch {
      /* ignore */
    }
    return
  }

  const doc = {
    tls: {
      certificates: rows.map((r) => ({ certFile: r.cert_path, keyFile: r.key_path })),
    },
  }
  const yaml = `# generated by tpm — custom certificates\n${stringify(doc)}`
  const tmp = `${finalPath}.tmp`
  writeFileSync(tmp, yaml, 'utf8')
  renameSync(tmp, finalPath)
}
