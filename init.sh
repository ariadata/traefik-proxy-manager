#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

UID_NUM="${UID:-1000}"
GID_NUM="${GID:-1000}"

dirs=(
  data/tpm
  data/tpm/custom-certs
  data/tpm/backups
  data/traefik
  logs/tpm
  logs/traefik
  configs/traefik/vhosts
)

for d in "${dirs[@]}"; do
  mkdir -p "$d"
done

ACME="data/traefik/acme.json"
if [[ ! -f "$ACME" ]]; then
  echo '{}' >"$ACME"
fi
chmod 600 "$ACME"

PROVIDERS_ENV="data/tpm/traefik-providers.env"
if [[ ! -f "$PROVIDERS_ENV" ]]; then
  echo '# generated by tpm — do not edit' >"$PROVIDERS_ENV"
fi

if [[ -f configs/traefik/traefik.base.yml && ! -f configs/traefik/traefik.yml ]]; then
  cp configs/traefik/traefik.base.yml configs/traefik/traefik.yml
fi

if [[ ! -f .env ]]; then
  cp example.env .env
  echo "created .env from example.env — set TPM_SECRETS_KEY"
fi

if command -v chown >/dev/null 2>&1; then
  chown -R "${UID_NUM}:${GID_NUM}" data logs configs/traefik/vhosts 2>/dev/null || true
fi

echo "init complete"
